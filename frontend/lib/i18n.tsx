export const translations: Record<Language, Record<TranslationKey, string>> = { en, vi };

interface I18nContextValue {
  language: Language;
  setLanguage: (lang: Language) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = React.createContext<I18nContextValue | null>(null);

function getInitialLanguage(): Language {
  if (typeof window === "undefined") return "en";
  const saved = window.localStorage.getItem(LANGUAGE_KEY);
  if (saved === "vi" || saved === "en") return saved;
  const nav = window.navigator?.language?.toLowerCase() ?? "";
  return nav.startsWith("vi") ? "vi" : "en";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = React.useState<Language>(getInitialLanguage);

  React.useEffect(() => {
    try {
      window.localStorage.setItem(LANGUAGE_KEY, language);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = React.useCallback((lang: Language) => setLanguageState(lang), []);
  const toggleLanguage = React.useCallback(() => setLanguageState((prev) => (prev === "en" ? "vi" : "en")), []);

  const t = React.useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => {
      let template = translations[language][key] ?? translations.en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          template = template.replaceAll(`{${k}}`, String(v));
        }
      }
      return template;
    },
    [language],
  );

  const value = React.useMemo(
    () => ({ language, setLanguage, toggleLanguage, t }),
    [language, setLanguage, toggleLanguage, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = React.useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
